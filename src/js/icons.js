/** Fill any empty <i data-icon> placeholders inside `root`. */
export function hydrateIcons(root = document) {
    root.querySelectorAll('i[data-icon]:empty').forEach((el) => {
        const tmp = document.createElement('template');
        tmp.innerHTML = icon(el.dataset.icon);
        el.innerHTML = tmp.content.firstElementChild.innerHTML;
    });
}
